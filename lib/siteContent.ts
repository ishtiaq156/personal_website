export function absoluteUrl(path: string) {
  if (path === "/") {
    return SITE_URL;
  }

  return `${SITE_URL}${path}`;
}

function pageMarkdown(title: string, paragraphs: string[]) {
  return [
    `# ${title}`,
    "",
    ...paragraphs,
    "",
    "## Useful Links",
    ...resourceLinks(),
  ]
    .join("\n")
    .trimEnd();
}

